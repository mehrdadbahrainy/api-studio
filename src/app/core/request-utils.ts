import { AuthMode, Environment, KeyValue, RequestDraft, row } from './models';

export class RequestValidationError extends Error { override name = 'RequestValidationError'; }
export function activeVariables(environment: Environment | undefined): Record<string, string> {
  const vars: Record<string, string> = Object.create(null);
  for (const item of environment?.variables ?? []) {
    if (item.enabled && item.key.trim()) vars[item.key.trim()] = item.value;
  }
  return vars;
}
export function interpolate(text: string, variables: Record<string, string>): string {
  return text.replace(/\{\{\s*([^{}]+?)\s*\}\}/g, (_full, raw: string) => {
    const key = raw.trim();
    if (!Object.prototype.hasOwnProperty.call(variables, key)) throw new RequestValidationError(`Missing environment variable: ${key}`);
    return variables[key];
  });
}
function appendEntries(target: Headers, items: KeyValue[], variables: Record<string, string>): void {
  for (const entry of items) {
    if (!entry.enabled || !entry.key.trim()) continue;
    const key = interpolate(entry.key.trim(), variables);
    try { target.set(key, interpolate(entry.value, variables)); }
    catch { throw new RequestValidationError(`Invalid header: ${key}`); }
  }
}
function authHeader(mode: AuthMode, draft: RequestDraft, vars: Record<string,string>): string | null {
  if (mode === 'bearer') {
    const token = interpolate(draft.bearerToken, vars).trim();
    if (!token) throw new RequestValidationError('Bearer token is empty.');
    return `Bearer ${token}`;
  }
  if (mode === 'basic') {
    const username = interpolate(draft.basicUsername, vars);
    const password = interpolate(draft.basicPassword, vars);
    // UTF-8 before Base64 is needed for non-ASCII credentials.
    const bytes = new TextEncoder().encode(`${username}:${password}`);
    let binary = ''; for (const byte of bytes) binary += String.fromCharCode(byte);
    return `Basic ${btoa(binary)}`;
  }
  return null;
}
export interface PreparedRequest { url: string; init: RequestInit; }
export function prepareRequest(draft: RequestDraft, environment?: Environment): PreparedRequest {
  const vars = activeVariables(environment);
  let url: URL;
  try { url = new URL(interpolate(draft.url.trim(), vars)); }
  catch { throw new RequestValidationError('Enter a valid absolute HTTP or HTTPS URL.'); }
  if (!['http:', 'https:'].includes(url.protocol)) throw new RequestValidationError('Only HTTP and HTTPS requests are supported.');
  if (url.username || url.password) throw new RequestValidationError('Put credentials in the Auth tab, not inside the URL.');
  for (const param of draft.params) {
    if (param.enabled && param.key.trim()) url.searchParams.append(interpolate(param.key.trim(), vars), interpolate(param.value, vars));
  }
  const headers = new Headers();
  appendEntries(headers, draft.headers, vars);
  const authorization = authHeader(draft.authMode, draft, vars);
  if (authorization) headers.set('Authorization', authorization);
  let body: BodyInit | undefined;
  if (draft.method !== 'GET' && draft.method !== 'HEAD') {
    switch (draft.bodyMode) {
      case 'none': break;
      case 'json': {
        body = interpolate(draft.body, vars);
        try { JSON.parse(body); } catch { throw new RequestValidationError('Request body is not valid JSON.'); }
        if (!headers.has('Content-Type')) headers.set('Content-Type','application/json');
        break;
      }
      case 'text': body = interpolate(draft.body, vars); if (!headers.has('Content-Type')) headers.set('Content-Type','text/plain; charset=utf-8'); break;
      case 'formdata': {
        const form = new FormData();
        for (const item of draft.formData) {
          if (item.enabled && item.key.trim()) form.append(interpolate(item.key.trim(), vars), interpolate(item.value, vars));
        }
        body = form;
        // Multipart boundaries must be generated by fetch. Don't set Content-Type here.
        headers.delete('Content-Type');
        break;
      }
      case 'urlencoded': {
        const parsed = interpolate(draft.body,vars);
        // The editor accepts a=1&b=2, URLSearchParams handles escaping on the wire.
        body = new URLSearchParams(parsed).toString();
        if (!headers.has('Content-Type')) headers.set('Content-Type','application/x-www-form-urlencoded');
        break;
      }
    }
  }
  return { url: url.toString(), init: { method:draft.method, headers, ...(body === undefined ? {} : {body}), redirect:'follow' } };
}
export function toEditableRows(headers: Headers): KeyValue[] { return [...headers.entries()].map(([key,value]) => row(key,value)); }
export function prettyBody(text: string, contentType: string): string {
  if (!text) return '';
  if (contentType.includes('json') || /^\s*[\[{]/.test(text)) {
    try { return JSON.stringify(JSON.parse(text), null, 2); } catch { /* leave non-JSON as plain text */ }
  }
  return text;
}
export function readableBytes(bytes: number): string { return bytes < 1024 ? `${bytes} B` : bytes < 1048576 ? `${(bytes/1024).toFixed(1)} KB` : `${(bytes/1048576).toFixed(2)} MB`; }
export function sanitizeExport(workspace: WorkspaceLike): WorkspaceLike {
  // Explicitly keep this a complete local backup; the caller warns before export.
  return structuredClone(workspace);
}
type WorkspaceLike = { [key:string]: unknown };
