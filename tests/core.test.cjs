const {test}=require('node:test');
const assert=require('node:assert/strict');
const {freshRequest,row,initialWorkspace}=require('../.test-dist/models.js');
const {prepareRequest,interpolate,RequestValidationError,prettyBody,readableBytes}=require('../.test-dist/request-utils.js');
const {parseWorkspace,addHistory}=require('../.test-dist/workspace-utils.js');

test('starter workspace has a working sample request',()=>{
 const w=initialWorkspace();assert.equal(w.version,1);assert.equal(w.collections.length,1);
 assert.equal(w.collections[0].requests.length,1);assert.equal(w.collections[0].requests[0].method,'GET');
});
test('environment replacement applies to URL, parameters and headers',()=>{
 const d=freshRequest();d.url='{{baseUrl}}/users?sort=asc';d.params=[row('page','{{page}}')];d.headers=[row('X-Env','{{page}}')];
 const env={id:'x',name:'test',variables:[row('baseUrl','https://example.org'),row('page','2')]};
 const p=prepareRequest(d,env);assert.equal(p.url,'https://example.org/users?sort=asc&page=2');assert.equal(p.init.headers.get('X-Env'),'2');
});
test('unresolved variables fail closed instead of silently sending wrong request',()=>{
 const d=freshRequest();d.url='https://example.org/{{missing}}';
 assert.throws(()=>prepareRequest(d),RequestValidationError);
});
test('scheme validation blocks javascript, file and malformed URLs',()=>{
 const d=freshRequest();for(const url of ['javascript:alert(1)','file:///etc/passwd','bad url','ftp://example.org']){d.url=url;assert.throws(()=>prepareRequest(d),RequestValidationError);}
});
test('a POST validates JSON body and supplies Content-Type',()=>{
 const d=freshRequest();d.method='POST';d.bodyMode='json';d.body='{"amount":1}';
 const p=prepareRequest(d);assert.equal(p.init.body,d.body);assert.equal(p.init.headers.get('content-type'),'application/json');
 d.body='{invalid';assert.throws(()=>prepareRequest(d),/not valid JSON/);
});
test('multipart form fields are supported and Content-Type boundary is generated by fetch',()=>{
 const d=freshRequest();d.method='POST';d.bodyMode='formdata';d.formData=[row('title','Test'),row('token','{{token}}')];
 d.headers=[row('Content-Type','multipart/form-data')];
 const p=prepareRequest(d,{id:'one',name:'one',variables:[row('token','alpha')]});
 assert.ok(p.init.body instanceof FormData);assert.equal(p.init.body.get('title'),'Test');
 assert.equal(p.init.body.get('token'),'alpha');assert.equal(p.init.headers.get('Content-Type'),null);
});
test('GET ignores body content',()=>{
 const d=freshRequest();d.method='GET';d.bodyMode='json';d.body='invalid';
 assert.equal(prepareRequest(d).init.body,undefined);
});
test('Bearer and Basic Auth are generated without leaking credentials in the URL',()=>{
 const d=freshRequest();d.authMode='bearer';d.bearerToken='{{token}}';
 let p=prepareRequest(d,{id:'x',name:'x',variables:[row('token','secret')]});
 assert.equal(p.init.headers.get('Authorization'),'Bearer secret');
 d.authMode='basic';d.basicUsername='maria';d.basicPassword='päss';
 p=prepareRequest(d);assert.equal(p.init.headers.get('Authorization'),'Basic '+Buffer.from('maria:päss','utf8').toString('base64'));
 d.url='https://u:p@example.org/';assert.throws(()=>prepareRequest(d),/credentials/);
});
test('URL-encoded form body normalizes encoding',()=>{
 const d=freshRequest();d.method='PUT';d.bodyMode='urlencoded';d.body='name=John+Smith&city=Tehran';
 const p=prepareRequest(d);assert.equal(p.init.body,'name=John+Smith&city=Tehran');
 assert.equal(p.init.headers.get('content-type'),'application/x-www-form-urlencoded');
});
test('workspace backup parses, validates and normalizes safely',()=>{
 const old=initialWorkspace();const restored=parseWorkspace(JSON.parse(JSON.stringify(old)));
 assert.equal(restored.collections[0].requests[0].name,'Get a sample TODO');
 assert.throws(()=>parseWorkspace({version:99}),/Not an API Studio/);
 assert.throws(()=>parseWorkspace({version:1,collections:'oops',environments:[]}),/collections and environments/);
});
test('history redacts bearer tokens, Basic passwords and auth-related headers',()=>{
 const d=freshRequest();d.authMode='bearer';d.bearerToken='PRIVATE';d.basicPassword='PRIVATE2';d.headers.push(row('Authorization','Bearer PRIVATE3'));
 const history=addHistory([],d,200,18);assert.equal(history[0].request.bearerToken,'');assert.equal(history[0].request.basicPassword,'');
 assert.ok(!history[0].request.headers.some(x=>x.key==='Authorization'));
});
test('history stays within bounded storage',()=>{
 const d=freshRequest();let history=[];for(let i=0;i<120;i++)history=addHistory(history,d,200,i);
 assert.equal(history.length,80);
});
test('output formatting prettifies JSON but keeps plain text unchanged',()=>{
 assert.equal(prettyBody('{"ok":true}','application/json'),'{\n  "ok": true\n}');
 assert.equal(prettyBody('hello','text/plain'),'hello');assert.equal(readableBytes(2048),'2.0 KB');
});
